/* Fills a quad of four vertices and six indices for each drawn character of a string, its
 * characters side by side from a screen position and clipped to the camera's raster; returns
 * the number of quads */
RwInt32 fn_8047832C(const RwChar *string, RwUInt32 count, RtCharset *charSet, RwInt32 x, RwInt32 y,
                    RwIm2DVertex *vertices, RwImVertexIndex *indices, RwImVertexIndex baseIndex,
                    RwBool hideSpaces) {
    RtCharsetDesc desc;
    RwInt32 screenHeight; /* first the font raster size, then the camera raster height */
    RwRaster *cameraRaster;
    RwInt32 screenWidth;
    RwReal recipHeight;
    RwReal halfTexelV;
    RwReal recipWidth;
    RwReal halfTexelU;
    RwReal nearZ;
    RwIm2DVertex *vertex;
    RwInt32 numQuads;
    RwInt32 nextIndex;
    RwImVertexIndex *index;
    const RwChar *character;
    RwInt32 numVertices;
    RwUInt32 i;

    fn_80478AE8(&desc, &screenHeight);
    recipHeight = 1.0f / (RwReal)charSet->height;
    recipWidth = 1.0f / (RwReal)charSet->width;
    cameraRaster = lbl_805F15B4->curCamera->frameBuffer;
    screenHeight = cameraRaster->height;
    screenWidth = cameraRaster->width;
    nearZ = RwIm2DGetNearScreenZ();
    halfTexelV = recipHeight * 0.5f;
    halfTexelU = recipWidth * 0.5f;
    if (!hideSpaces) {
        lbl_805EDE70 = '\0';
    }

    vertex = vertices;
    index = indices;
    character = string;
    nextIndex = baseIndex;
    numQuads = 0;
    for (i = 0, numVertices = 0; i < count; i++, character++) {
        RwInt32 left;
        RwInt32 top;
        RwInt32 right;
        RwInt32 bottom;

        if (lbl_805EDE70 == *character) {
            continue;
        }
        top = y;
        bottom = y + desc.height;
        left = x + desc.width * i;
        right = left + desc.width;
        if (y < screenHeight && bottom > 0 && left < screenWidth && right > 0) {
            RwUInt32 code = *character - ' ';
            RwInt32 u0 = (code % desc.tile_width) * desc.width_internal;
            RwInt32 v0 = (code / desc.tile_width) * desc.height_internal;
            RwInt32 u1 = u0 + desc.width;
            RwInt32 v1 = v0 + desc.height;
            RwReal uLeft;
            RwReal vTop;
            RwReal vBottom;
            RwReal uRight;
            RwInt32 k;

            if (y < 0) {
                v0 -= y;
                top = 0;
            }
            if (bottom > screenHeight - 1) {
                bottom = screenHeight - 1;
                v1 = v0 + (bottom - top);
            }
            if (left < 0) {
                u0 -= left;
                left = 0;
            }
            if (right > screenWidth - 1) {
                right = screenWidth - 1;
                u1 = u0 + (right - left);
            }

            uLeft = recipWidth * (RwReal)u0 + halfTexelU;
            vTop = recipHeight * (RwReal)v0 + halfTexelV;
            vertex[0].u = uLeft;
            vertex[0].v = vTop;
            vBottom = recipHeight * (RwReal)v1 + halfTexelV;
            vertex[1].u = uLeft;
            vertex[1].v = vBottom;
            uRight = recipWidth * (RwReal)u1 + halfTexelU;
            vertex[2].u = uRight;
            vertex[2].v = vBottom;
            vertex[3].u = uRight;
            vertex[3].v = vTop;
            vertex[0].x = (RwReal)left;
            vertex[0].y = (RwReal)top;
            vertex[1].x = (RwReal)left;
            vertex[1].y = (RwReal)bottom;
            vertex[2].x = (RwReal)right;
            vertex[2].y = (RwReal)bottom;
            vertex[3].x = (RwReal)right;
            vertex[3].y = (RwReal)top;

            for (k = 0; k < 4; k++) {
                vertices[numVertices + k].z = nearZ;
                vertices[numVertices + k].emissiveColor.red = 255;
                vertices[numVertices + k].emissiveColor.green = 255;
                vertices[numVertices + k].emissiveColor.blue = 255;
                vertices[numVertices + k].emissiveColor.alpha = 255;
            }
            vertex += 4;
            numVertices += 4;
            numQuads++;

            index[0] = nextIndex;
            index[1] = nextIndex + 1;
            index[2] = nextIndex + 2;
            index[3] = nextIndex;
            index[4] = nextIndex + 2;
            index[5] = nextIndex + 3;
            index += 6;
            nextIndex += 4;
        }
    }
    return numQuads;
}

/* Prints a string at a screen position, drawing it with alpha blending and no depth test */
RtCharset *fn_80478700(RtCharset *charSet, const RwChar *string, RwInt32 x, RwInt32 y) {
    RwUInt32 verticesSize;
    RwUInt32 indicesSize;
    RwIm2DVertex *vertices;
    RwImVertexIndex *indices;
    RwInt32 numQuads;
    RwUInt32 length;
    void *zTest;
    void *zWrite;
    void *srcBlend;
    void *destBlend;
    void *raster;
    void *filter;
    void *cullMode;

    length = strlen(string);
    if (length == 0) {
        return charSet;
    }
    verticesSize = length * 4 * sizeof(RwIm2DVertex);
    vertices = RwMalloc(verticesSize, rwMEMHINTDUR_FUNCTION | rwID_CHARSET);
    indicesSize = length * 6 * sizeof(RwImVertexIndex);
    indices = RwMalloc(indicesSize, rwMEMHINTDUR_FUNCTION | rwID_CHARSET);
    if (vertices == NULL || indices == NULL) {
        if (vertices != NULL) {
            RwFree(vertices);
        }
        if (indices != NULL) {
            RwFree(indices);
        }
        RWERROR((E_RW_NOMEM, verticesSize + indicesSize));
        return NULL;
    }

    numQuads = fn_8047832C(string, length, charSet, x, y, vertices, indices, 0, FALSE);
    if (numQuads <= 0) {
        RwFree(indices);
        RwFree(vertices);
        return NULL;
    }

    RwRenderStateGet(rwRENDERSTATEZTESTENABLE, &zTest);
    RwRenderStateGet(rwRENDERSTATEZWRITEENABLE, &zWrite);
    RwRenderStateGet(rwRENDERSTATESRCBLEND, &srcBlend);
    RwRenderStateGet(rwRENDERSTATEDESTBLEND, &destBlend);
    RwRenderStateGet(rwRENDERSTATETEXTURERASTER, &raster);
    RwRenderStateGet(rwRENDERSTATETEXTUREFILTER, &filter);
    RwRenderStateGet(rwRENDERSTATECULLMODE, &cullMode);

    RwRenderStateSet(rwRENDERSTATEZTESTENABLE, (void *)FALSE);
    RwRenderStateSet(rwRENDERSTATEZWRITEENABLE, (void *)FALSE);
    RwRenderStateSet(rwRENDERSTATETEXTUREFILTER, (void *)rwFILTERNEAREST);
    RwRenderStateSet(rwRENDERSTATETEXTURERASTER, charSet);
    RwRenderStateSet(rwRENDERSTATESRCBLEND, (void *)rwBLENDSRCALPHA);
    RwRenderStateSet(rwRENDERSTATEDESTBLEND, (void *)rwBLENDINVSRCALPHA);
    RwRenderStateSet(rwRENDERSTATECULLMODE, (void *)rwCULLMODECULLNONE);

    RwIm2DRenderIndexedPrimitive(rwPRIMTYPETRILIST, vertices, numQuads * 4, indices, numQuads * 6);

    RwRenderStateSet(rwRENDERSTATEZTESTENABLE, zTest);
    RwRenderStateSet(rwRENDERSTATEZWRITEENABLE, zWrite);
    RwRenderStateSet(rwRENDERSTATESRCBLEND, srcBlend);
    RwRenderStateSet(rwRENDERSTATEDESTBLEND, destBlend);
    RwRenderStateSet(rwRENDERSTATETEXTURERASTER, raster);
    RwRenderStateSet(rwRENDERSTATETEXTUREFILTER, filter);
    RwRenderStateSet(rwRENDERSTATECULLMODE, cullMode);

    RwFree(indices);
    RwFree(vertices);
    return charSet;
}

